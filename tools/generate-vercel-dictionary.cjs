const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const sourcePath = path.join(root, "src/main/java/com/compilador/lexer/Diccionario.java");
const outputPath = path.join(
  root,
  "traductor_frontend/traductor-frontend/api/_lib/dictionary.generated.cjs",
);

const source = fs.readFileSync(sourcePath, "utf8");
const entries = new Map();
const forcedEsEn = new Map();
const forcedEnEs = new Map();

function unescapeJavaString(value) {
  return value
    .replace(/\\"/g, "\"")
    .replace(/\\n/g, "\n")
    .replace(/\\r/g, "\r")
    .replace(/\\t/g, "\t")
    .replace(/\\\\/g, "\\");
}

function add(word, type, translation) {
  const key = word.toLowerCase();
  entries.set(key, { tipo: type, traduccion: translation });
}

const operations = [];
const string = String.raw`"((?:\\.|[^"\\])*)"`;

for (const match of source.matchAll(new RegExp(String.raw`add\(${string}\s*,\s*${string}\s*,\s*${string}\s*\);`, "g"))) {
  operations.push({
    index: match.index,
    kind: "add",
    word: unescapeJavaString(match[1]),
    type: unescapeJavaString(match[2]),
    translation: unescapeJavaString(match[3]),
  });
}

for (const match of source.matchAll(new RegExp(String.raw`addBidireccionales\(${string}\s*,\s*new String\[\]\[\]\s*\{([\s\S]*?)\}\s*\);`, "g"))) {
  operations.push({
    index: match.index,
    kind: "bidir",
    type: unescapeJavaString(match[1]),
    body: match[2],
  });
}

for (const match of source.matchAll(new RegExp(String.raw`traduccionesForzadas(ES_EN|EN_ES)\.put\(${string}\s*,\s*${string}\s*\);`, "g"))) {
  operations.push({
    index: match.index,
    kind: match[1],
    word: unescapeJavaString(match[2]),
    translation: unescapeJavaString(match[3]),
  });
}

operations.sort((a, b) => a.index - b.index);

for (const operation of operations) {
  if (operation.kind === "add") {
    add(operation.word, operation.type, operation.translation);
    continue;
  }

  if (operation.kind === "bidir") {
    const pairRe = new RegExp(String.raw`\{\s*${string}\s*,\s*${string}\s*\}`, "g");
    for (const pair of operation.body.matchAll(pairRe)) {
      const left = unescapeJavaString(pair[1]);
      const right = unescapeJavaString(pair[2]);
      add(left, operation.type, right);
      add(right, operation.type, left);
    }
    continue;
  }

  const target = operation.kind === "ES_EN" ? forcedEsEn : forcedEnEs;
  target.set(operation.word.toLowerCase(), operation.translation);
}

const payload = {
  entries: Object.fromEntries([...entries.entries()].sort(([a], [b]) => a.localeCompare(b))),
  forcedEsEn: Object.fromEntries([...forcedEsEn.entries()].sort(([a], [b]) => a.localeCompare(b))),
  forcedEnEs: Object.fromEntries([...forcedEnEs.entries()].sort(([a], [b]) => a.localeCompare(b))),
};

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(
  outputPath,
  `// Generated by tools/generate-vercel-dictionary.cjs from src/main/java/com/compilador/lexer/Diccionario.java.\nmodule.exports = ${JSON.stringify(payload, null, 2)};\n`,
  "utf8",
);

console.log(`Generated ${entries.size} dictionary entries at ${outputPath}`);
